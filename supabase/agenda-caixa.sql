-- Lançamento automático: os horários finalizados de cada profissional viram o lançamento do dia (origem "agenda"),
-- que soma com os outros no ranking. Só quando a agenda própria é a oficial (sem AppBarber conectada).
create or replace function public.ag_lancar_dia(p_company uuid, p_barber text, p_dia date) returns void language plpgsql security definer set search_path = public as $$
declare res jsonb; n int;
begin
  if exists (select 1 from public.integrations i where i.company_id = p_company and coalesce(i.est_code, '') <> '') then return; end if;
  select count(*) into n from public.ag_agendamentos a where a.company_id = p_company and a.barber_id = p_barber and a.status = 'finalizado' and (a.inicio at time zone 'America/Sao_Paulo')::date = p_dia;
  if n = 0 then delete from public.entries where id = 'ag_' || p_barber || '_' || p_dia; return; end if;
  with ag as (select * from public.ag_agendamentos a where a.company_id = p_company and a.barber_id = p_barber and a.status = 'finalizado' and (a.inicio at time zone 'America/Sao_Paulo')::date = p_dia),
       sv as (select s->>'nome' nome, coalesce((s->>'preco')::numeric, 0) preco from ag, jsonb_array_elements(ag.servicos) s),
       pr as (select coalesce((p->>'qtd')::numeric, 1) qtd, coalesce((p->>'preco')::numeric, 0) preco from ag, jsonb_array_elements(ag.produtos) p),
       nomes as (select nome, count(*) q, sum(preco) v from sv where coalesce(nome, '') <> '' group by nome)
  select jsonb_strip_nulls(jsonb_build_object(
      'fat', round((select sum(valor) from ag), 2),
      'serv', (select count(*) from sv),
      'servV', round((select coalesce(sum(preco), 0) from sv), 2),
      'cli', (select count(distinct coalesce(cliente_id::text, nullif(cliente_fone, ''), cliente_nome)) from ag),
      'prod', (select coalesce(sum(qtd), 0) from pr),
      'prodV', round((select coalesce(sum(qtd * preco), 0) from pr), 2),
      'comanda', round((select max(valor) from ag), 2),
      'hOcup', round((select sum(extract(epoch from (fim - inicio))) / 3600 from ag)::numeric, 2),
      'svc', (select jsonb_object_agg(nome, jsonb_build_array(q, round(v, 2))) from nomes)))
    into res;
  insert into public.entries (id, company_id, barber_id, date, data, source, updated_at)
    values ('ag_' || p_barber || '_' || p_dia, p_company, p_barber, p_dia, res, 'agenda', now())
    on conflict (barber_id, date, source) do update set data = excluded.data, updated_at = now();
end $$;
revoke all on function public.ag_lancar_dia(uuid, text, date) from public, anon, authenticated;

create or replace function public.ag_lancar_trg() returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op in ('UPDATE', 'DELETE') and (old.status = 'finalizado') then perform public.ag_lancar_dia(old.company_id, old.barber_id, (old.inicio at time zone 'America/Sao_Paulo')::date); end if;
  if tg_op in ('INSERT', 'UPDATE') and new.status = 'finalizado' then perform public.ag_lancar_dia(new.company_id, new.barber_id, (new.inicio at time zone 'America/Sao_Paulo')::date); end if;
  return null;
end $$;
drop trigger if exists ag_lancar on public.ag_agendamentos;
create trigger ag_lancar after insert or update or delete on public.ag_agendamentos for each row execute function public.ag_lancar_trg();
